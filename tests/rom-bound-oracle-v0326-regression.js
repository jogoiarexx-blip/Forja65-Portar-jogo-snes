const assert=require('assert');
const C=require('../forja65-core.js');
const rom=C.loadRom(C.makeSyntheticRom(),'synthetic.sfc');
const hash=C.romFingerprint(rom);
assert.strictEqual(hash.length,16);
const good=`rom=${hash} target=008000 from=008010 kind=FLOW e=1 m=1 x=1 c=0 observed=1`;
const bad=`rom=0000000000000000 target=008100 from=008010 kind=FLOW e=1 m=1 x=1 c=0 observed=1`;
const merged=C.mergeRuntimeHints(good,bad,good);
const hs=C.parseRuntimeHints(merged);
assert.strictEqual(hs.length,2);
assert.strictEqual(hs.find(h=>h.rom===hash).observed,2);
const a=C.analyze(rom,65536,merged);
assert.strictEqual(a.romFingerprint,hash);
assert.strictEqual(a.runtimeHintsRejected,1);
assert.ok(a.runtimeHintsImported>=1);
const files=C.generateProject(rom,a);
assert.ok(files['forja65-build-manifest.txt'].includes('rom_fingerprint='+hash));
assert.ok(files['src/runtime.hpp'].includes('FORJA65_INPUT_REPLAY'));
assert.ok(files['CMakeLists.txt'].includes('FORJA65_STRICT'));
assert.ok(files['tests/equivalence_runner.cpp']);
console.log('ROM_BOUND_ORACLE_V0326_PASS',{hash,rejected:a.runtimeHintsRejected,imported:a.runtimeHintsImported});
