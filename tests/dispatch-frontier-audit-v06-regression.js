'use strict';
const assert=require('node:assert/strict');
const A=require('../tools/dispatch-frontier-audit.js');
const rom='1234567890abcdef';
const text=`rom=${rom} target=81856E from=818151 kind=FLOW e=0 m=0 x=0 c=1 observed=5\nrom=${rom} target=818A32 from=818151 kind=FLOW e=0 m=1 x=0 c=1 observed=3\nrom=${rom} target=80841F from=808384 kind=STACK-RTL e=0 m=0 x=0 c=0 observed=2\nrom=ffffffffffffffff target=80841F from=808384 kind=FLOW e=0 m=0 x=0 c=0 observed=1\ninvalid\n`;
const compiled=`{0x81856Eu,false,false,false,true,true,&sub,0x81856Eu},\n{0x818A32u,false,true,false,false,false,&sub,0x818A32u},\n{0x80841Fu,false,false,true,true,false,&sub,0x80841Fu},`;
const d=A.parseDispatch(compiled);
assert.equal(d.size,3);
const r=A.audit(text,d,rom);
assert.equal(r.observed_edges,3);
assert.equal(r.callable_edges,2);
assert.equal(r.unresolved_edges,1);
assert.equal(r.stale_rom_hints,1);
assert.equal(r.malformed_hint_lines,1);
assert.equal(r.missing[0].target,'$80841F');
assert.equal(r.sites.find(x=>x.from==='$818151').observed_edges,2);
assert.equal(A.variantMatches({e:false,m:false,x:false,carryKnown:false,c:false},{e:false,m:false,x:false,c:true}),true);
assert.equal(A.variantMatches({e:false,m:false,x:false,carryKnown:true,c:false},{e:false,m:false,x:false,c:true}),false);
assert.throws(()=>A.parseOptions(['--unknown']),/Unknown/);
console.log('dispatch-frontier-audit-v06-regression: PASS');
