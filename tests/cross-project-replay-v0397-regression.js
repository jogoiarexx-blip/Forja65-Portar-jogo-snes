'use strict';
const assert=require('assert');
const crypto=require('crypto');
const C=require('../forja65-core');
const {makeCrossfeed}=require('../tools/cross-project-replay');
const rom=C.makeSyntheticRom(),romObj=C.loadRom(rom);
for(const pc of [0x808060,0x808075,0x808090])romObj.data[C.snesToRom(romObj,pc)]=0xDB; // synthetic STP at observed destinations
const fnv=C.romFingerprint(romObj);
const sha=crypto.createHash('sha256').update(romObj.data).digest('hex');
const knowledge={schema:'forja65.knowledge.v1',rom:{fnv1a64:fnv,sha256:sha},entries:[{address:0x808060,name:'from-static-only',category:'UNKNOWN',priority:15,state:{emulation:false,m8:false,x8:false,carry:null},evidence:['static catalog, not observed']}],dataRegions:[],dispatch:[]};
const integration={schema:'dkc3.bidirectional-evidence.v1',rom:{fnv1a64:fnv,sha256:sha,bytes:romObj.data.length},zero_to_native:{later_observed_flow:{site:'808040',target:'808060',semantic_equivalence_proven:false},latest_recorded_flow:{from:0x808070,target:0x808075,flags:{e:0,m:0,x:0,c:1},evidence_level:'ZERO runtime observed; not native semantic proof'},latest_recorded_cpu_failure:{pc:0x808080,destination:0x808090,e:0,m:0,x:0,c:1}}};
const tail=(pc,c)=>`${pc} A=0 X=0 Y=0 S=1ff D=0 DB=80 PB=80 P=5 E=0 M=0 X8=0 C=${c}\n`;
const opts={romBytes:rom,integration,knowledge,traceText:tail('808040',0),errorText:`fluxo CFG nao resolvido em pc=${0x808040} target=${0x808060}`,priorTraceText:tail('808070',1),priorErrorText:`fluxo CFG nao resolvido em pc=${0x808070} target=${0x808075}`,stateText:'808080 -> 808090 e=0 m=0 x=0 c=1\n'};
const result=makeCrossfeed(opts);
assert.strictEqual(result.report.imported_runtime_observations,3);
assert.strictEqual(C.parseRuntimeHints(result.hints).length,3);
assert(result.hints.includes('target=808060 from=808040 kind=FLOW e=0 m=0 x=0 c=0'));
assert(result.hints.includes('target=808075 from=808070 kind=FLOW e=0 m=0 x=0 c=1'));
assert(result.hints.includes('target=808090 from=808080 kind=STATE e=0 m=0 x=0 c=1'));
assert(!result.hints.includes('from-static-only'));
assert(result.knowledge.entries.some(e=>e.address===0x808060&&e.state.carry===false));
assert.strictEqual(result.knowledge.dispatch.length,0);
assert.throws(()=>makeCrossfeed({...opts,romBytes:new Uint8Array(rom).fill(9,0,1)}),/ROM|Cabecalho/);
assert.throws(()=>makeCrossfeed({...opts,integration:{...integration,rom:{...integration.rom,sha256:'0'.repeat(64)}}}),/ROM/);
assert.throws(()=>makeCrossfeed({...opts,knowledge:{...knowledge,rom:{...knowledge.rom,sha256:'0'.repeat(64)}}}),/ROM/);
const continued=makeCrossfeed({...opts,followupTraceText:tail('8080A0',1),followupErrorText:`fluxo CFG nao resolvido em pc=${0x8080A0} target=${0x8080B0}`});
assert.strictEqual(continued.report.imported_runtime_observations,4);
assert(continued.hints.includes('target=8080B0 from=8080A0 kind=FLOW e=0 m=0 x=0 c=1'));
assert.throws(()=>makeCrossfeed({...opts,followupTraceText:tail('8080A0',1)}),/Followup/);
assert.throws(()=>makeCrossfeed({...opts,followupTraceText:tail('8080A1',1),followupErrorText:`fluxo CFG nao resolvido em pc=${0x8080A0} target=${0x8080B0}`}),/PC/);
assert.throws(()=>makeCrossfeed({...opts,traceText:tail('808041',0)}),/PC/);
assert.throws(()=>makeCrossfeed({...opts,errorText:'fluxo CFG nao resolvido em pc=1 target=2'}),/FLOW/);
assert.throws(()=>makeCrossfeed({...opts,priorTraceText:tail('808070',0)}),/flags/);
assert.throws(()=>makeCrossfeed({...opts,stateText:'808080 -> 808090 e=0 m=0 x=0 c=0'}),/STATE/);
assert.throws(()=>makeCrossfeed({...opts,integration:{...integration,zero_to_native:{...integration.zero_to_native,later_observed_flow:{...integration.zero_to_native.later_observed_flow,semantic_equivalence_proven:true}}}}),/observacao/);
const synthetic=C.loadRom(rom);
// The generated dispatcher must contain actual compilable state-specific entries;
// knowledge labels alone are not enough.
const source=C.generateProject(synthetic,C.analyze(synthetic,750,C.parseRuntimeHints(result.hints)));
assert(source['src/dispatch.cpp'].includes('0x808090u,false,false,false,true,true'));
assert(source['src/dispatch.cpp'].includes('0x808060u,false,false,false,true,false'));
console.log('cross-project-replay-v0397-regression: OK');
