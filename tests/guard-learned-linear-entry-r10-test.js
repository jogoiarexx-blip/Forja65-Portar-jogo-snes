'use strict';
const assert = require('assert');
const {restrict}=require('../tools/guard-learned-linear-entry.js');
const rom=Buffer.alloc(524288,0xea);
rom[0x25D57]=0xe2;rom[0x25D58]=0x20;
const dispatch='{0x04DD59u,false,true,false,false,false,&sample,0x04DD59u},\n';
const shard=`void dummy() {\nL_04DD57:\n// $04DD57 SEP\nhw.advanceCpuInstruction(1);\ncpu.sep(0x20u);\ngoto L_04DD59;\nL_04DD59:\n return;\n}\n`;
const args={romBytes:rom,shardText:shard,dispatchText:dispatch,pc:0x04dd57,state:'M1X0'};
const result=restrict(args);
assert.equal(result.changed,true);
assert.equal(result.branches,1);
assert(result.text.includes('hw.requestDispatch('));
assert.equal(restrict({...args,shardText:result.text}).changed,false);
assert.throws(()=>restrict({...args,dispatchText:''}),/lacks exact-state/);
assert.throws(()=>restrict({...args,state:'E1'}),/State/);
assert.throws(()=>restrict({...args,pc:0x04dd58}),/Only deterministic/);
assert.throws(()=>restrict({...args,shardText:shard.replace('// $04DD57 SEP','// $04DD57 INC')}),/differs/);
assert.throws(()=>restrict({...args,shardText:shard.replace('goto L_04DD59;','goto L_04DD60;')}),/Expected 1-4/);
console.log('PASS: guard-learned-linear-entry R10 (7 assertions)');
