'use strict';
const assert=require('node:assert/strict');
const F=require('../forja65-core.js');
const base=F.makeSyntheticRom();
const regular=F.loadRom(base);
const normalFiles=F.generateProject(regular,F.analyze(regular,256));
assert.match(normalFiles['src/dispatch.cpp'],/void forja65_dispatch_restored\(/);
assert.match(normalFiles['src/dispatch.cpp'],/FORJA65_CPU_BACKEND/);
assert.match(normalFiles['src/runtime.hpp'],/void writeCx4Qa\(/);
assert.match(normalFiles['src/runtime.hpp'],/hdmaIdleSkipEnabled/);
assert.match(normalFiles['src/main.cpp'],/hw\.writeCx4Qa\(qa\)/);
assert.match(normalFiles['src/runtime.hpp'],/lo>=0x2140&&lo<=0x217F/);
const x2=F.makeSyntheticRom();
x2[0x7fbf]=0x10;x2[0x7fd6]=0xf3;
const cx4Rom=F.loadRom(x2);
assert.equal(cx4Rom.header.coprocessor,'CX4');
const cx4Files=F.generateProject(cx4Rom,F.analyze(cx4Rom,256));
assert.match(cx4Files['src/runtime.hpp'],/void syncCx4\(/);
assert.match(cx4Files['src/runtime.hpp'],/void appendCx4FrameAudit\(/);
assert.match(cx4Files['src/runtime.hpp'],/cx4_instruction_count=/);
assert.match(cx4Files['CMakeLists.txt'],/FORJA65_REQUIRE_CX4/);
assert.match(cx4Files['BUILD-WINDOWS.cmd'],/INSTALAR-CX4-WINDOWS/);
const launcher=cx4Files['INSTALAR-CX4-WINDOWS.cmd'];
assert.ok(launcher.startsWith('@echo off\r\n'));
assert.equal(launcher.replace(/\r\n/g,'').includes('\n'),false);
const manifest=cx4Files['forja65-build-manifest.txt'];
assert.ok(manifest.includes('INSTALAR-CX4-WINDOWS.cmd'));
assert.ok(manifest.includes('tools/cx4_real_qa.py'));
assert.ok(cx4Files['src/runtime.hpp'].includes('cpuIrqInterruptPending=cx4IrqLevel;'));
console.log('REV165_CROSS_INTEGRATION_GENERATED_PROJECT_PASS nonCX4+CX4 checkpoint APU HDMA CPU QA CRLF');
