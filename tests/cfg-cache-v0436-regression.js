'use strict';
const assert=require('node:assert/strict');
const F=require('../forja65-core.js');
const {makeCfgCache,mergeCfgCoverage,isAuditedCacheVersion}=require('../tools/project-io.js');
const rom=F.loadRom(F.makeSyntheticRom(),'cache-v0436.sfc');
const analysis=F.analyze(rom,384),hash=F.romFingerprint(rom);
const previous={...makeCfgCache(analysis,hash),version:'0.4.35-pcm-dsp-fir-noise'};
assert.equal(isAuditedCacheVersion(previous.version),false);
assert.equal(isAuditedCacheVersion('0.4.34-ppu-mode7-math'),false);
assert.equal(isAuditedCacheVersion('0.4.29-crossfeed-6-branches'),false);
assert.equal(isAuditedCacheVersion('0.4.24-audio-key-timing'),false);
assert.throws(()=>mergeCfgCoverage(F.analyze(rom,384),previous,hash),/incompatible/);
const result=mergeCfgCoverage(F.analyze(rom,384),makeCfgCache(analysis,hash),hash);
assert.equal(result.a.decoded,analysis.decoded);
assert.throws(()=>mergeCfgCoverage(F.analyze(rom,384),previous,'different-rom'),/incompatible/);
assert.throws(()=>mergeCfgCoverage(F.analyze(rom,384),{...previous,version:'0.4.35-fake'},hash),/incompatible/);
const runtime=F.generateProject(rom,result.a)['src/runtime.hpp'];
assert.ok(runtime.includes('dmaTransferByte'));
assert.ok(runtime.includes('sramSaveError'));
console.log('CFG_CACHE_V0436_PASS old_cache=rejected current_cache=retained runtime=regenerated guards=kept');
