'use strict';
const assert=require('node:assert/strict');
const C=require('../forja65-core.js');
const rom=C.loadRom(C.makeSyntheticRom(),'fixture.sfc');
const a=C.analyze(rom,512);
const unproven=C.generateProject(rom,a);
const bare=unproven['src/dispatch.cpp'];
assert.match(bare,/std::binary_search\(std::begin\(kForja65StackReturnOffsets\)/);
assert.match(bare,/if\(i>=kForja65AliasCount\|\|kForja65Aliases\[i\]\.off!=off\)return false;/);
assert.match(bare,/kForja65StackReturnOffsets\[\]=\{0xFFFFFFFFu\};/);
assert.match(unproven['src/runtime.hpp'],/expected=/);
assert.match(unproven['src/runtime.hpp'],/depth=/);
const liveCallee=a.functions.flatMap(f=>f.instructions).find(i=>i.mnemonic==='RTS');
assert.ok(liveCallee,'fixture has RTS');
a.syntheticReturnTargets=[liveCallee.pc];
const proven=C.generateProject(rom,a)['src/dispatch.cpp'];
const off=C.snesToRom(rom,liveCallee.pc);
assert.ok(off!==null);
assert.match(proven,new RegExp('kForja65StackReturnOffsets\\[\\]=\\{0x'+C.hex(off,6)+'u\\}'));
assert.doesNotMatch(proven,/kForja65StackReturnOffsets\[\]=\{0xFFFFFFFFu\}/);
console.log('STACK_RETURN_AUTHORIZATION_V0365_PASS target=$'+C.hex(liveCallee.pc,6));
